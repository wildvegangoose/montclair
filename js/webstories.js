MW.storiesFor = function (number, road) {
  if (!number || !road) return [];
  const norm = r => r.toUpperCase().replace(/[^A-Z ]/g, "")
    .replace(/\bN\b/g, "NORTH").replace(/\bS\b/g, "SOUTH").replace(/\bE\b/g, "EAST").replace(/\bW\b/g, "WEST")
    .replace(/\bUP\b/g, "UPPER")
    .replace(/\bGLEN\s+RIDGE\b/g, "GLENRIDGE")
    .replace(/\bCLAIRMONT\b/g, "CLAREMONT")
    .replace(/\bBELLEVIEW\b/g, "BELLEVUE")
    .replace(/\bSAINT\s+LUKES?\b/g, "ST LUKES")
    .replace(/\b(ROAD|RD|AVENUE|AVE|AV|STREET|ST|PLACE|PL|TERRACE|TER|DRIVE|DR|LANE|LN|COURT|CT|WAY|CRESCENT|CRES)\b/g, "")
    .replace(/\s+/g, " ").trim();
  return MW.webStories.filter(s => {
    const m = s.address.match(/^(\d+)\s+(.+)$/);
    return m && m[1] === String(number) && norm(m[2]) === norm(road);
  });
};
